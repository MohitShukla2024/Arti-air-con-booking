/**
 * scripts/inject-sw-config.mjs
 *
 * SECURITY (C-03): Build-time script that generates public/firebase-messaging-sw.js
 * from environment variables. This ensures Firebase credentials are never hardcoded
 * in source code — they are injected from env vars at build time.
 *
 * Reads from:
 *   1. process.env (already set — Vercel production, CI/CD environments)
 *   2. .env file (local development — parsed manually without requiring dotenv package)
 *
 * Run automatically via:
 *   - `npm run dev` (via predev script)
 *   - `npm run build` (via prebuild script)
 */

import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

// ─── Step 1: Load .env file if present (for local dev) ───────────────────────
function loadDotenv() {
  const envPath = join(ROOT, ".env");
  if (!existsSync(envPath)) return;

  const content = readFileSync(envPath, "utf-8");
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eqIdx = trimmed.indexOf("=");
    if (eqIdx === -1) continue;

    const key = trimmed.slice(0, eqIdx).trim();
    let val = trimmed.slice(eqIdx + 1).trim();

    // Remove surrounding quotes
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }

    // Only set if not already in process.env (process.env takes priority)
    if (!(key in process.env)) {
      process.env[key] = val;
    }
  }
}

loadDotenv();

// ─── Step 2: Read Firebase config from env vars ───────────────────────────────
const config = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || "",
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || "",
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "",
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || "",
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || "",
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || "",
};

const missing = Object.entries(config)
  .filter(([, v]) => !v)
  .map(([k]) => k);

if (missing.length > 0) {
  console.warn(
    `[inject-sw-config] Warning: Missing env vars for service worker: ${missing.join(", ")}\n` +
    `  Service worker will be generated with empty values. Push notifications may not work.\n` +
    `  Add these variables to your .env file or Vercel Environment Variables.`
  );
}

// ─── Step 3: Generate service worker content ──────────────────────────────────
const SW_CONTENT = `// Firebase Cloud Messaging & Web Push Service Worker for Arti Air Con
// AUTO-GENERATED by scripts/inject-sw-config.mjs — DO NOT EDIT MANUALLY
// Re-generated on every build from environment variables.
// Generated: ${new Date().toISOString()}

importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js");

const firebaseConfig = ${JSON.stringify(config, null, 2)};

firebase.initializeApp(firebaseConfig);
const messaging = firebase.messaging();

// ─── Background Message Handler ─────────────────────────────────────────────
messaging.onBackgroundMessage(function (payload) {
  console.log("[firebase-messaging-sw.js] Background message received:", payload);

  const notificationTitle =
    payload.notification?.title ||
    payload.data?.title ||
    "Arti Air Con";

  const notificationBody =
    payload.notification?.body ||
    payload.data?.body ||
    "You have a new notification.";

  const notificationUrl =
    payload.data?.url || "/dashboard";

  const notificationOptions = {
    body: notificationBody,
    icon: "/icons/icon-192x192.png",
    badge: "/icons/icon-72x72.png",
    data: {
      url: notificationUrl,
      bookingId: payload.data?.bookingId || null,
    },
    requireInteraction: false,
    tag: payload.data?.bookingId || "arti-notification",
  };

  self.registration.showNotification(notificationTitle, notificationOptions);
});

// ─── Notification Click Handler ──────────────────────────────────────────────
self.addEventListener("notificationclick", function (event) {
  event.notification.close();

  const url = event.notification.data?.url || "/dashboard";

  event.waitUntil(
    clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then(function (clientList) {
        for (const client of clientList) {
          if (client.url === url && "focus" in client) {
            return client.focus();
          }
        }
        if (clients.openWindow) {
          return clients.openWindow(url);
        }
      })
  );
});
`;

// ─── Step 4: Write to public/firebase-messaging-sw.js ────────────────────────
const outputPath = join(ROOT, "public", "firebase-messaging-sw.js");
writeFileSync(outputPath, SW_CONTENT, "utf-8");

console.log("[inject-sw-config] ✓ Generated public/firebase-messaging-sw.js from environment variables.");
